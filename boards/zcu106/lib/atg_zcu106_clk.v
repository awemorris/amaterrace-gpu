/*
 * atg_zcu106_clk: Clock and reset management for the AMD / Xilinx Zynq
 * UltraScale+ ZCU106 evaluation kit (xczu7ev-ffvc1156-2-e).
 *
 * Synthesizes the 400 MHz GPU core logic clock (period 2.500 ns) from the
 * 100 MHz PS reference clock (pl_clk0) using UltraScale+ MMCME4_BASE:
 *   - Input: 100.0 MHz (CLKIN1_PERIOD = 10.000 ns)
 *   - VCO: 100.0 MHz * 12.000 = 1200.0 MHz (within 800 - 1600 MHz limits)
 *   - Output 0: 1200.0 MHz / 3.000 = 400.0 MHz (clk_gpu)
 *   - Output 1: 1200.0 MHz / 6.000 = 200.0 MHz (clk_axi, for PS-PL AXI interface)
 *
 * Synchronous active-low resets (rst_n_gpu, rst_n_axi) are generated by
 * gating the external reset with MMCM locked, passed through 2-stage
 * synchronizers (am_sync) per domain.
 */

`timescale 1ns / 1ps
`default_nettype none

module atg_zcu106_clk #(
	parameter real CLKIN_PERIOD = 10.000,	/* 100 MHz pl_clk0 default */
	parameter real CLKFBOUT_MULT = 12.000,	/* VCO = 1200 MHz */
	parameter real CLKOUT0_DIV = 3.000,	/* 400 MHz clk_gpu */
	parameter integer CLKOUT1_DIV = 6	/* 200 MHz clk_axi */
) (
	input wire clk_in,
	input wire rst_in,	/* active-high raw reset (e.g. !pl_resetn0 or CPU_RESET) */
	output wire clk_gpu,
	output wire rst_n_gpu,
	output wire clk_axi,
	output wire rst_n_axi,
	output wire locked
);
	wire clkfb_out, clkfb_in;
	wire clk_gpu_unbuf, clk_axi_unbuf;
	wire mmcm_locked;

	MMCME4_BASE #(
		.BANDWIDTH("OPTIMIZED"),
		.CLKIN1_PERIOD(CLKIN_PERIOD),
		.DIVCLK_DIVIDE(1),
		.CLKFBOUT_MULT_F(CLKFBOUT_MULT),
		.CLKFBOUT_PHASE(0.000),
		.CLKOUT0_DIVIDE_F(CLKOUT0_DIV),
		.CLKOUT0_PHASE(0.000),
		.CLKOUT0_DUTY_CYCLE(0.500),
		.CLKOUT1_DIVIDE(CLKOUT1_DIV),
		.CLKOUT1_PHASE(0.000),
		.CLKOUT1_DUTY_CYCLE(0.500),
		.STARTUP_WAIT("FALSE")
	) mmcm_gpu (
		.CLKIN1(clk_in),
		.CLKFBIN(clkfb_in),
		.RST(rst_in),
		.PWRDWN(1'b0),
		.CLKFBOUT(clkfb_out),
		.CLKFBOUTB(),
		.CLKOUT0(clk_gpu_unbuf),
		.CLKOUT0B(),
		.CLKOUT1(clk_axi_unbuf),
		.CLKOUT1B(),
		.CLKOUT2(),
		.CLKOUT2B(),
		.CLKOUT3(),
		.CLKOUT3B(),
		.CLKOUT4(),
		.CLKOUT5(),
		.CLKOUT6(),
		.LOCKED(mmcm_locked)
	);

	BUFG bufg_fb (
		.I(clkfb_out),
		.O(clkfb_in)
	);

	BUFG bufg_gpu (
		.I(clk_gpu_unbuf),
		.O(clk_gpu)
	);

	BUFG bufg_axi (
		.I(clk_axi_unbuf),
		.O(clk_axi)
	);

	assign locked = mmcm_locked;

	/* Reset synchronizers: assert immediately on reset or loss of lock */
	wire raw_rst_n = !rst_in && mmcm_locked;

	am_sync sync_rst_gpu (
		.clk(clk_gpu),
		.rst_n(raw_rst_n),
		.d(1'b1),
		.q(rst_n_gpu)
	);

	am_sync sync_rst_axi (
		.clk(clk_axi),
		.rst_n(raw_rst_n),
		.d(1'b1),
		.q(rst_n_axi)
	);

endmodule

`default_nettype wire
