#!/usr/bin/env python3
# fw-formats.py: writes fw/cp/formats.inc, the CP firmware's table of the
# formats the GPU has (tools/fmtmodel.py, FORMATS: the same table as
# include/atg_fmt_info.vh) and the sRGB encoder's thresholds (fmtmodel's
# srgb_tables): what the firmware needs to lay out images, to pick the
# blitter's pixel size and to pack clear values into a format's bits.
#   fw_formats[]   one row per format, in VkFormat order: the VkFormat, the
#                  bytes of a texel (or of a 4x4 block), the components, the
#                  type (fmtmodel's numbers), the flags ([0] depth, [1]
#                  stencil in [31:24], [2] compressed block, [3] colour
#                  attachment, [4] linear filter) and per component (R, G,
#                  B, A) its lowest bit and its width.
#   fw_srgb_thr[]  the smallest fp32 above EOTF((i + 0.5) / 255), i =
#                  0..254: the nearest 8-bit sRGB code of a linear x in
#                  [0, 1] is the count of thresholds <= x.
# The generated file is in git.
#   python3 -I tools/fw-formats.py           (writes the file)
#   python3 -I tools/fw-formats.py --check   (exit 1 if the file differs)
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fmtmodel as F  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fw', 'cp', 'formats.inc')


def text():
    _, thr = F.srgb_tables()
    lines = ['/*', ' * Amaterrace GPU', ' * Copyright (C) 2026 Awe Morris', ' *',
             ' * SPDX-License-Identifier: Zlib', ' */', '',
             '/*',
             ' * formats.inc: the formats the GPU has and the sRGB thresholds, for',
             ' * format.c.  Generated by tools/fw-formats.py from tools/fmtmodel.py; do',
             ' * not edit.',
             ' */', '',
             '/*',
             ' * The formats, in VkFormat order: {VkFormat, bytes, components, type,',
             ' * flags, {lowest bit, width} of R, G, B, A}.',
             ' */',
             'static const struct fw_format fw_formats[] = {']
    for v in sorted(F.FORMATS):
        f = F.FORMATS[v]
        img = f.feat.partition('|')[0]
        flags = int(f.depth) | int(f.stencil) << 1 | int(f.block) << 2
        flags |= int('C' in img) << 3 | int('F' in img) << 4
        chans = list(f.chans) + [(0, 0)] * (4 - len(f.chans))
        comp = ', '.join('{ %d, %d }' % c for c in chans)
        lines.append('\t{ %d, %d, %d, %d, 0x%02X, { %s } },\t/* %s */' %
                     (v, f.nbytes, len(f.chans), f.ty, flags, comp, f.name))
    lines += ['};', '',
              '/*',
              ' * The sRGB encoder\'s thresholds: the smallest fp32 above the EOTF of',
              ' * (i + 0.5) / 255, i = 0..254.',
              ' */',
              'static const uint32_t fw_srgb_thr[255] = {']
    for i in range(0, 255, 6):
        lines.append('\t' + ' '.join('0x%08X,' % t for t in thr[i:i + 6]))
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    t = text()
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        with open(OUT) as f:
            if f.read() != t:
                print('fw-formats: %s is out of date' % OUT)
                return 1
        print('fw-formats: %s is current' % OUT)
        return 0
    with open(OUT, 'w') as f:
        f.write(t)
    print('fw-formats: wrote %s (%d formats)' % (OUT, len(F.FORMATS)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
