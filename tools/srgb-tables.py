#!/usr/bin/env python3
# srgb-tables.py: writes include/atg_srgb.vh, the sRGB tables of the format
# functions, from the sRGB transfer function (the Khronos Data Format
# Specification's definition: EOTF(u) = u / 12.92 for u <= 0.04045, else
# ((u + 0.055) / 1.055)^2.4), computed with 60-digit decimals in
# tools/fmtmodel.py (srgb_tables):
#   atg_srgb_dec(c)  fp32 of EOTF(c / 255), rounded to nearest even;
#   atg_srgb_thr(i)  the smallest fp32 above EOTF((i + 0.5) / 255),
#                    i = 0..254 (255 reads +infinity): the nearest 8-bit
#                    code of a linear x in [0, 1] is the count of
#                    thresholds <= x (atg_fmt_srgbenc).
# The generated file is in git.
#   python3 -I tools/srgb-tables.py           (writes the file)
#   python3 -I tools/srgb-tables.py --check   (exit 1 if the file differs)
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fmtmodel as F  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'include', 'atg_srgb.vh')


def text():
    dec, thr = F.srgb_tables()
    lines = ['/*', ' * Amaterrace GPU', ' * Copyright (C) 2026 Awe Morris', ' *',
             ' * SPDX-License-Identifier: Zlib', ' */', '',
             '/*',
             ' * atg_srgb.vh: the sRGB tables, included inside a module.  Generated by',
             ' * tools/srgb-tables.py; do not edit.',
             ' *   atg_srgb_dec(c)  fp32 of the sRGB EOTF of c / 255 (nearest even).',
             ' *   atg_srgb_thr(i)  the smallest fp32 above the EOTF of (i + 0.5) / 255,',
             ' *                    i = 0..254; 255 reads +infinity.',
             ' */', '',
             'function [31:0] atg_srgb_dec;', '\tinput [7:0] c;', '\tcase (c)']
    for c in range(256):
        lines.append("\t8'd%d: atg_srgb_dec = 32'h%08X;" % (c, dec[c]))
    lines += ['\tdefault: atg_srgb_dec = 32\'h00000000;', '\tendcase', 'endfunction', '',
              'function [31:0] atg_srgb_thr;', '\tinput [7:0] i;', '\tcase (i)']
    for c in range(255):
        lines.append("\t8'd%d: atg_srgb_thr = 32'h%08X;" % (c, thr[c]))
    lines += ["\tdefault: atg_srgb_thr = 32'h7F800000;", '\tendcase', 'endfunction', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    t = text()
    if '--check' in sys.argv:
        with open(OUT) as fd:
            same = fd.read() == t
        print('PASS srgb-tables.check' if same else 'FAIL srgb-tables.check: %s differs' % OUT)
        sys.exit(0 if same else 1)
    with open(OUT, 'w') as fd:
        fd.write(t)
    print('srgb-tables: wrote include/atg_srgb.vh')
