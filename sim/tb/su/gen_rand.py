#!/usr/bin/env python3
# Writes rand.s: a seeded random integer program for the SU testbench
# (ALU ops on r1-r24 with random sources, immediates and specials, and
# masked sections with exec.and / exec.set).  Run by tools/su-tests.sh.
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
import random
import sys

R = ["add", "sub", "sll", "slt", "sltu", "xor", "srl", "sra", "or", "and", "min", "max",
     "minu", "maxu", "andn", "orn", "xnor"]
I = ["addi", "slti", "sltiu", "xori", "ori", "andi"]
S = ["slli", "srli", "srai"]
SP = ["lane", "warp", "lidn", "exec", "zero", "onei", "mask", "one", "mone"]


def main(out, seed=7, n=400):
    rnd = random.Random(seed)
    lines = ["# generated by gen_rand.py (seed %d)" % seed]
    for r in range(1, 25):
        lines.append("movi r%d, 0x%08x" % (r, rnd.getrandbits(32)))
        lines.append("add r%d, r%d, %s" % (r, r, rnd.choice(["lane", "lidn", "warp"])))
    masked = False
    for _ in range(n):
        k = rnd.random()
        src = lambda: ("r%d" % rnd.randint(1, 24)) if rnd.random() < 0.85 else rnd.choice(SP)
        d = rnd.randint(1, 24)
        if k < 0.5:
            lines.append("%s r%d, %s, %s" % (rnd.choice(R), d, src(), src()))
        elif k < 0.7:
            lines.append("%s r%d, %s, %d" % (rnd.choice(I), d, src(), rnd.randint(-2048, 2047)))
        elif k < 0.78:
            lines.append("%s r%d, %s, %d" % (rnd.choice(S), d, src(), rnd.randint(0, 31)))
        elif k < 0.83:
            lines.append("sel r%d, %s, %s, %s" % (d, src(), src(), src()))
        elif k < 0.87:
            lines.append("movi r%d, %d" % (d, rnd.getrandbits(32)))
        elif k < 0.93 and not masked:
            lines.append("exec.save r30")
            lines.append("slt r29, r%d, r%d" % (rnd.randint(1, 24), rnd.randint(1, 24)))
            lines.append("exec.and r29")
            masked = True
        elif masked:
            lines.append("exec.set r30")
            masked = False
    if masked:
        lines.append("exec.set r30")
    lines.append("end")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
