#!/usr/bin/env python3
# Writes frand.s: a seeded random float program for the SU testbench: fp32
# arithmetic with random rounding modes, modifiers and sat, compares,
# conversions, fround/fract, the integer multiplies, the transcendentals and
# the divider (long results right before their use: the scoreboard), sel and
# masked sections; specials (0, -0, inf, NaN, denormals, huge) in some lanes.
# Run by tools/su-tests.sh.
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
import random
import sys

F2 = ["fadd.s", "fsub.s", "fmul.s", "fmin.s", "fmax.s", "fsgnj.s"]
F3 = ["fmadd.s", "fmsub.s", "fnmsub.s", "fnmadd.s"]
CMP = ["feq.s", "flt.s", "fle.s", "fne.s"]
CVT = ["fcvt.w.s", "fcvt.wu.s"]
I2F = ["fcvt.s.w", "fcvt.s.wu"]
XU = ["rcp", "rsq", "exp2", "log2", "sin", "cos", "fsqrt.s"]
DIV = ["div", "divu", "rem", "remu"]
MUL = ["mul", "mulh", "mulhsu", "mulhu"]
RM = ["", "", "", ", rne", ", rtz", ", rdn", ", rup", ", rmm"]
SPECIALS = [0x00000000, 0x80000000, 0x7F800000, 0xFF800000, 0x7FC00000, 0x00400000,
            0x7F7FFFFF, 0x3F800000, 0xBF000000, 0x4B000001, 0x00800000]


def main(out, seed=11, n=400):
    rnd = random.Random(seed)
    L = ["# generated by gen_frand.py (seed %d)" % seed]
    # r1-r20: floats from the lane number, scaled; r21-r24 integers.
    for r in range(1, 21):
        L.append("addi r30, lidn, %d" % rnd.randint(-80, 80))
        L.append("fcvt.s.w r%d, r30" % r)
        L.append("movi r31, 0x%08x" % (rnd.randint(0x3C000000, 0x41000000) |
                                       rnd.getrandbits(1) << 31))
        L.append("fmul.s r%d, r%d, r31" % (r, r))
        if rnd.random() < 0.5:
            # A special value in the lanes below a random lane number.
            L.append("movi r31, 0x%08x" % rnd.choice(SPECIALS))
            L.append("slti r30, lane, %d" % rnd.randint(1, 6))
            L.append("sel r%d, r30, r31, r%d" % (r, r))
    for r in range(21, 25):
        L.append("movi r%d, 0x%08x" % (r, rnd.getrandbits(32)))
        L.append("xor r%d, r%d, lidn" % (r, r))
    masked = False

    def fs():
        x = "r%d" % rnd.randint(1, 20) if rnd.random() < 0.9 else rnd.choice(
            ["one", "half", "two", "mone", "zero"])
        k = rnd.random()
        if k < 0.1:
            return "-" + x
        if k < 0.15:
            return "|%s|" % x
        if k < 0.18:
            return "-|%s|" % x
        return x

    def isrc():
        return "r%d" % rnd.randint(21, 24) if rnd.random() < 0.8 else rnd.choice(
            ["lidn", "lane", "onei"])

    for _ in range(n):
        k = rnd.random()
        d = rnd.randint(1, 20)
        sat = ".sat" if rnd.random() < 0.08 else ""
        if k < 0.30:
            o = rnd.choice(F2)
            rm = rnd.choice(RM) if o in ("fadd.s", "fsub.s", "fmul.s") else ""
            L.append("%s%s r%d, %s, %s%s" % (o, sat, d, fs(), fs(), rm))
        elif k < 0.45:
            L.append("%s%s r%d, %s, %s, %s%s" % (rnd.choice(F3), sat, d, fs(), fs(), fs(),
                                                rnd.choice(RM)))
        elif k < 0.52:
            # A compare, then a select on it.
            L.append("%s r29, %s, %s" % (rnd.choice(CMP), fs(), fs()))
            L.append("sel r%d, r29, r%d, r%d" % (d, rnd.randint(1, 20), rnd.randint(1, 20)))
        elif k < 0.57:
            L.append("%s r%d, %s%s" % (rnd.choice(CVT), rnd.randint(21, 24), fs(),
                                       rnd.choice(RM)))
        elif k < 0.61:
            L.append("%s r%d, %s%s" % (rnd.choice(I2F), d, isrc(), rnd.choice(RM)))
        elif k < 0.65:
            L.append("fround.s%s r%d, %s, %s" % (sat, d, fs(), rnd.choice(
                ["rne", "rtz", "rdn", "rup"])))
        elif k < 0.68:
            L.append("fract%s r%d, %s" % (sat, d, fs()))
        elif k < 0.73:
            # A transcendental, often used right away.
            L.append("%s r%d, %s" % (rnd.choice(XU), d, fs()))
            if rnd.random() < 0.5:
                L.append("fmul.s r%d, r%d, %s" % (rnd.randint(1, 20), d, fs()))
        elif k < 0.76:
            L.append("%s r%d, %s, %s" % (rnd.choice(DIV), rnd.randint(21, 24), isrc(), isrc()))
        elif k < 0.86:
            L.append("%s r%d, %s, %s" % (rnd.choice(MUL), rnd.randint(21, 24), isrc(), isrc()))
        elif k < 0.95 and not masked:
            L.append("exec.save r28")
            L.append("flt.s r27, %s, %s" % (fs(), fs()))
            L.append("exec.and r27")
            masked = True
        elif masked:
            L.append("exec.set r28")
            masked = False
    if masked:
        L.append("exec.set r28")
    L.append("end")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
